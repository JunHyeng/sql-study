DROP DATABASE IF EXISTS shop;
CREATE DATABASE shop DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE shop;

-- 고객
CREATE TABLE customers (
    customer_id      INT          PRIMARY KEY,
    name             VARCHAR(20)  NOT NULL,
    gender           CHAR(1)      NOT NULL,              -- M / F
    birth_year       INT          NOT NULL,
    city             VARCHAR(10)  NOT NULL,              -- 거주 지역(시·도)
    signup_date      DATE         NOT NULL,              -- 가입일
    email            VARCHAR(50)  UNIQUE,                -- 없을 수 있음
    phone            VARCHAR(20),                        -- 없을 수 있음
    marketing_agree  TINYINT(1)   NOT NULL DEFAULT 0,    -- 마케팅 수신 동의 (1=동의)
    referred_by      INT,                                -- 추천인 고객번호 (없으면 NULL)
    FOREIGN KEY (referred_by) REFERENCES customers(customer_id)
);

-- 상품
CREATE TABLE products (
    product_id    INT          PRIMARY KEY,
    name          VARCHAR(50)  NOT NULL,
    category      VARCHAR(10)  NOT NULL,                 -- 상의/하의/아우터/신발/가방/액세서리
    brand         VARCHAR(20)  NOT NULL,
    price         INT          NOT NULL CHECK (price > 0),   -- 정가
    cost          INT          NOT NULL CHECK (cost > 0),    -- 원가
    launched_at   DATE         NOT NULL,                 -- 출시일
    is_active     TINYINT(1)   NOT NULL DEFAULT 1        -- 판매중 1 / 단종 0
);

-- 주문 (주문 1건 = 결제 1번)
CREATE TABLE orders (
    order_id       INT          PRIMARY KEY,
    customer_id    INT          NOT NULL,
    ordered_at     DATETIME     NOT NULL,                -- 주문 일시 (날짜+시간)
    status         VARCHAR(10)  NOT NULL,                -- 배송완료 / 취소 / 반품
    channel        VARCHAR(5)   NOT NULL,                -- 앱 / 웹
    coupon_amount  INT          NOT NULL DEFAULT 0,      -- 쿠폰 할인액
    shipping_fee   INT          NOT NULL DEFAULT 0,      -- 배송비 (5만원 이상 무료)
    FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

-- 주문 상세
CREATE TABLE order_items (
    order_item_id  INT  PRIMARY KEY,
    order_id       INT  NOT NULL,
    product_id     INT  NOT NULL,
    quantity       INT  NOT NULL CHECK (quantity > 0),
    unit_price     INT  NOT NULL,                        -- 실제 판매 단가 (할인 반영, 정가와 다를 수 있음)
    FOREIGN KEY (order_id)   REFERENCES orders(order_id),
    FOREIGN KEY (product_id) REFERENCES products(product_id)
);

-- 직원
CREATE TABLE employees (
    emp_id      INT          PRIMARY KEY,
    name        VARCHAR(20)  NOT NULL,
    dept        VARCHAR(20)  NOT NULL,
    position    VARCHAR(10)  NOT NULL,
    manager_id  INT,                                     -- 직속 상사 emp_id (대표는 NULL)
    hire_date   DATE         NOT NULL,
    salary      INT          NOT NULL,                   -- 연봉(원)
    FOREIGN KEY (manager_id) REFERENCES employees(emp_id)
);

-- 조회용 인덱스 (2단계 1강에서 설명)
CREATE INDEX idx_orders_ordered_at ON orders (ordered_at);
CREATE INDEX idx_orders_customer   ON orders (customer_id);

